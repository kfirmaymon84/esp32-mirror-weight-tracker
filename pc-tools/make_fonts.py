"""Generate the Halo UI smooth fonts (TFT_eSPI .vlw format) as C arrays.

The firmware renders Outfit (numerals) and Inter (UI text) as anti-aliased
TFT_eSPI "smooth fonts". Instead of Processing's Create_font sketch this script
rasterises the glyphs with Pillow/FreeType and writes the same VLW layout, then
embeds every font in esp32-mirror/src/halo_fonts.h (app flash), so fonts ship
with the firmware .bin — including OTA updates — and never touch LittleFS.

Usage (TTFs from github.com/google/fonts, ofl/outfit and ofl/inter):
    python pc-tools/make_fonts.py --outfit "Outfit[wght].ttf" --inter "Inter[opsz,wght].ttf"

VLW layout (big-endian int32 unless noted), as read by TFT_eSPI loadFont():
    header : glyphCount, version(11), size, 0, ascent, descent
    glyphs : per glyph  unicode, height, width, xAdvance, dY(top above baseline), dX, 0
    bitmaps: per glyph  width*height bytes of 8-bit alpha
    trailer: name strings (ignored by TFT_eSPI)
"""

import argparse
import os
import struct

from PIL import ImageFont

ASCII = "".join(chr(c) for c in range(32, 127)) + "·−…’°"
DIGITS = "0123456789"

# name, family, px size, weight, character set
FONTS = [
    ("F_I10",   "inter",  10, 500, ASCII),                       # rail labels, axis labels
    ("F_I11",   "inter",  11, 400, ASCII),                       # captions
    ("F_I11B",  "inter",  11, 600, ASCII),                       # caps labels, pills
    ("F_I13",   "inter",  13, 400, ASCII),                       # body
    ("F_I15B",  "inter",  15, 600, ASCII),                       # greeting, tile values, buttons
    ("F_I22B",  "inter",  22, 600, ASCII),                       # screen titles
    ("F_O18",   "outfit", 18, 500, DIGITS + ".:-+− "),      # clock, small stats
    ("F_O26",   "outfit", 26, 500, DIGITS + ".:-+− kglb"),  # stats, deltas
    ("F_O62",   "outfit", 62, 500, DIGITS + ".-"),               # hero weight
    ("F_O52",   "outfit", 52, 500, DIGITS + ".-"),               # hero, 5 glyphs (100.0 / lb)
    ("F_O60L",  "outfit", 60, 300, DIGITS + ":"),                # night clock
    ("F_O80L",  "outfit", 80, 300, DIGITS + ".-"),               # live weight
    ("F_O64L",  "outfit", 64, 300, DIGITS + ".-"),               # live weight, 5 glyphs
]


def load(path, size, wght):
    f = ImageFont.truetype(path, size)
    axes = f.get_variation_axes()
    vals = []
    for a in axes:
        name = a.get("name", b"")
        name = name.decode() if isinstance(name, bytes) else str(name)
        if name.lower().startswith("weight"):
            vals.append(wght)
        elif name.lower().startswith("optical"):
            vals.append(max(a["minimum"], min(a["maximum"], size)))
        else:
            vals.append(a["default"])
    if vals:
        f.set_variation_by_axes(vals)
    return f


def vlw(font, size, chars):
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        if ch == " ":
            glyphs.append((32, 0, 0, round(font.getlength(" ")), 0, 0, b""))
            continue
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        bmp = bytes(mask)
        adv = round(font.getlength(ch))
        glyphs.append((ord(ch), h, w, adv, -oy, ox, bmp))
    ascent = max(g[4] for g in glyphs)
    descent = max(g[1] - g[4] for g in glyphs)
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for u, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    out += b"\x00\x00\x00\x00"
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--outfit", required=True)
    ap.add_argument("--inter", required=True)
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--out", default=os.path.join(here, "..", "esp32-mirror", "src", "halo_fonts.h"))
    a = ap.parse_args()
    paths = {"outfit": a.outfit, "inter": a.inter}

    parts = ["// Generated by pc-tools/make_fonts.py — do not edit.\n"
             "// Outfit and Inter (SIL Open Font License 1.1) as TFT_eSPI smooth fonts.\n"
             "#pragma once\n#include <pgmspace.h>\n"]
    total = 0
    for name, fam, size, wght, chars in FONTS:
        data = vlw(load(paths[fam], size, wght), size, chars)
        total += len(data)
        print(f"{name:8s} {fam:6s} {size:3d}px w{wght}  {len(data):6d} bytes")
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
        parts.append(f"\n// {fam} {size}px weight {wght}\n"
                     f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n")
    with open(a.out, "w", newline="\n", encoding="utf-8") as f:
        f.write("".join(parts))
    print(f"total {total} bytes -> {os.path.normpath(a.out)}")


if __name__ == "__main__":
    main()
